// Native crypto engine for the Flutter app, bridged to Dart via flutter_rust_bridge.
//
// This wraps `matrix-sdk-crypto` — the same Apache-2.0 crate whose WASM build
// (`@matrix-org/matrix-sdk-crypto-wasm`) already powers cluborbit-web's end-to-end encryption —
// so both clients share one audited crypto implementation instead of two separate ones. The API
// surface here intentionally mirrors the lifecycle cluborbit-web's chatService.js already
// implements (see that file for the reference behavior each of these is meant to match):
//   1. create/load a persistent OlmMachine for this device
//   2. feed it sync data (device list changes, to-device messages, one-time-key counts)
//   3. share/receive Megolm room keys
//   4. encrypt outgoing room events / decrypt incoming ones
//   5. cross-signing + secret storage + key backup, so history is readable across devices
//
// Status: step 1 of that list (persistent machine creation + identity keys) plus the
// flutter_rust_bridge scaffolding itself (this file's frb_generated module, regenerated by
// `flutter_rust_bridge_codegen generate` whenever the public API below changes — never hand-edit
// frb_generated.rs/.dart). Not yet run against a live homeserver; `cargo build`/`cargo test` are
// the only verification available in this environment so far.
//
// NOTE: `mod frb_generated;` must stay as the very first item in this file — plain `//` comments
// (not `//!` inner doc comments) are used here specifically so codegen re-injecting that line up
