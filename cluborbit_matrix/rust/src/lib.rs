#[derive(Debug)]
pub struct CryptoError {
    pub message: String,
}

impl std::fmt::Display for CryptoError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}
impl std::error::Error for CryptoError {}

// No blanket `impl<E: Display> From<E> for CryptoError` here — it collides with the standard
// library's own reflexive `impl<T> From<T> for T`. Call sites use `.map_err(CryptoError::from)`
// against these specific conversions instead.
impl From<ruma::IdParseError> for CryptoError {
    fn from(err: ruma::IdParseError) -> Self {
        CryptoError { message: err.to_string() }
    }
}
impl From<serde_json::Error> for CryptoError {
    fn from(err: serde_json::Error) -> Self {
        CryptoError { message: err.to_string() }
    }
}

// matrix-sdk-crypto is deliberately transport-agnostic — it hands back abstract "requests" you're
// responsible for actually sending, then hands the response back in. This is that pump, generic
// over every request kind the machine can produce: Dart's REST client (matrix_low_level_client.dart)
// already knows how to make an authenticated HTTP call given a method/path/body, so this keeps ALL
// Matrix-protocol-specific knowledge (which endpoint, which HTTP method, how the body is shaped —
// some request types serialize directly, others need their fields remapped into the real wire
// shape) inside Rust, where it's checked against ruma's real types, rather than duplicated in Dart.
pub struct PendingRequest {
    /// Echoed back to `mark_request_as_sent` once the HTTP call completes — matrix-sdk-crypto uses
    /// this to match a response to the request that produced it.
    pub id: String,
    /// Which of the fixed set of request kinds this is (e.g. "keys_upload") — also echoed back,
    /// so `mark_request_as_sent` knows which response type to parse the JSON as.
    pub kind: String,
    pub method: String,
    pub path: String,
    pub body_json: String,
}

/// The requests `bootstrap_cross_signing` needs sent, in order: device keys (if any are still
/// missing) first, then the cross-signing keys themselves, then the signatures that tie them
/// together. Each must be sent and fed back through `mark_request_as_sent` in that order, same as
/// `outgoing_requests`'s results.
pub struct CrossSigningBootstrap {
    pub upload_keys_req: Option<PendingRequest>,
    pub upload_signing_keys_req: PendingRequest,
    pub upload_signatures_req: PendingRequest,
}

impl CryptoSession {
    /// Requests that need to be sent to the homeserver right now — call this after every
    /// meaningful state change (after `create`, after `receive_sync_changes`, after
    /// `share_room_key`) and send each one, then report the result back via
    /// `mark_request_as_sent`. Mirrors the same "drain outgoing requests" loop chatService.js
    /// doesn't need to do explicitly because matrix-js-sdk's higher-level Client drives it
    /// internally — here we're one layer lower, so the Dart side has to drive it.
    pub async fn outgoing_requests(&self) -> Result<Vec<PendingRequest>, CryptoError> {
        let requests =
            self.machine.outgoing_requests().await.map_err(|e| CryptoError { message: e.to_string() })?;

        let mut pending = Vec::new();
        for request in requests {
            let id = request.request_id().to_string();
            if let Some(entry) = outgoing_request_entry(id, request.request())? {
                pending.push(entry);
            }
        }

        Ok(pending)
    }

    /// Feeds the HTTP response for a request `outgoing_requests` handed you back into the
    /// machine, identified by the same id/kind pair. Must be called for every request returned by
    /// `outgoing_requests` (skipping one — e.g. because the HTTP call failed — just means it'll be
    /// handed back again next time `outgoing_requests` is called).
    pub async fn mark_request_as_sent(
        &self,
        id: String,
        kind: String,
        response_json: String,
    ) -> Result<(), CryptoError> {
        let request_id: &TransactionId = id.as_str().into();
        match kind.as_str() {
            "keys_upload" => {
                let response = parse_response::<upload_keys::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "keys_query" => {
                let response = parse_response::<get_keys::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "keys_claim" => {
                let response = parse_response::<claim_keys::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "to_device" => {
                let response = parse_response::<send_event_to_device::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "signature_upload" => {
                let response = parse_response::<upload_signatures::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "keys_backup" => {
                let response = parse_response::<add_backup_keys::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, &response)
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            "signing_keys_upload" => {
                // No `From<&Response> for AnyIncomingResponse` impl exists for this one (unlike
                // every other kind above) — construct the variant directly instead.
                let response = parse_response::<upload_signing_keys::v3::Response>(response_json)?;
                self.machine
                    .mark_request_as_sent(request_id, CryptoAnyIncomingResponse::SigningKeysUpload(&response))
                    .await
                    .map_err(|e| CryptoError { message: e.to_string() })?;
            }
            other => {
                return Err(CryptoError { message: format!("Unknown request kind: {other}") });
            }
        }
        Ok(())
    }

    /// Feeds one `/sync` response's crypto-relevant pieces into the machine: to-device events
    /// (each as a raw JSON string, exactly as received), the user IDs whose device lists changed
    /// or left, and the one-time-key counts per algorithm (e.g. {"signed_curve25519": 47}).
    /// Returns the to-device events that were actually processed (decrypted where needed) as JSON
    /// strings, for the Dart side to hand to whatever already deals with to-device events (key
    /// verification requests, etc.).
    pub async fn receive_sync_changes(
        &self,
        to_device_events_json: Vec<String>,
        changed_device_users: Vec<String>,
        left_device_users: Vec<String>,
        // (algorithm, count) pairs rather than a BTreeMap<String, u64> — flutter_rust_bridge has
        // no simple-type support for BTreeMap and opaque-wraps it instead, which leaves Dart with
        // no way to actually construct one to pass in here. A list of pairs is a plain Dart
        // List<(String, int)>, buildable directly from the sync response's JSON map.
        one_time_key_counts: Vec<(String, u64)>,
    ) -> Result<Vec<String>, CryptoError> {
        let to_device_events: Vec<Raw<AnyToDeviceEvent>> = to_device_events_json
            .iter()
            .map(|json| Raw::from_json_string(json.clone()))
            .collect::<Result<_, _>>()?;

        let changed: Vec<_> =
            changed_device_users.iter().map(|u| UserId::parse(u.as_str())).collect::<Result<_, _>>()?;
        let left: Vec<_> =
            left_device_users.iter().map(|u| UserId::parse(u.as_str())).collect::<Result<_, _>>()?;
        let mut device_lists = ruma::api::client::sync::sync_events::DeviceLists::default();
        device_lists.changed = changed;
        device_lists.left = left;

        let key_counts: BTreeMap<OneTimeKeyAlgorithm, ruma::UInt> = one_time_key_counts
            .into_iter()
            .map(|(k, v)| (OneTimeKeyAlgorithm::from(k), ruma::UInt::new(v).unwrap_or_default()))
            .collect();

        let changes = EncryptionSyncChanges {
            to_device_events,
            changed_devices: &device_lists,
            one_time_keys_counts: &key_counts,
            unused_fallback_keys: None,
            next_batch_token: None,
        };

        let (events, _room_key_updates) = self
            .machine
            .receive_sync_changes(changes)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;

        Ok(events.iter().map(|e| e.as_raw().json().get().to_string()).collect())
    }

    /// Adds the given users (room members) to the machine's tracked-users list, flagging any not
    /// seen before for an immediate `/keys/query` — which then comes out of the next
    /// `outgoing_requests` drain. Without this the machine only ever knows about devices of users
    /// that happened to show up in a sync's `device_lists.changed`, so a room key would never be
    /// shared with anyone else's devices. Call this (then drain) before `ensure_sessions_for_users`.
    pub async fn update_tracked_users(&self, user_ids: Vec<String>) -> Result<(), CryptoError> {
        let users: Vec<_> = user_ids.iter().map(|u| UserId::parse(u.as_str())).collect::<Result<_, _>>()?;
        // Boxed as an owned `dyn Future + Send`: update_tracked_users' future borrows the user IDs,
        // which trips rustc's higher-ranked Send check inside flutter_rust_bridge's async wrapper.
        let machine = self.machine.clone();
        let fut: std::pin::Pin<Box<dyn std::future::Future<Output = _> + Send>> = Box::pin(async move {
            let user_refs: Vec<&UserId> = users.iter().map(|u| &**u).collect();
            machine.update_tracked_users(user_refs).await
        });
        fut.await.map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(())
    }

    /// Returns the `/keys/claim` request needed to set up 1-to-1 Olm sessions with every device of
    /// the given users that doesn't have one yet, or None when none are missing. This request is
    /// NOT part of `outgoing_requests` — matrix-sdk-crypto hands it back only here — so the caller
    /// must send it and feed the response to `mark_request_as_sent` (kind "keys_claim") before
    /// `share_room_key`, otherwise the room key is silently withheld from those devices and they
    /// show "unable to decrypt".
    pub async fn ensure_sessions_for_users(&self, user_ids: Vec<String>) -> Result<Option<PendingRequest>, CryptoError> {
        let users: Vec<_> = user_ids.iter().map(|u| UserId::parse(u.as_str())).collect::<Result<_, _>>()?;
        let user_refs: Vec<&UserId> = users.iter().map(|u| u.as_ref()).collect();
        let missing = self
            .machine
            .get_missing_sessions(user_refs.iter().copied())
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        match missing {
            Some((txn_id, request)) => Ok(Some(request_to_pending(txn_id.to_string(), "keys_claim", request)?)),
            None => Ok(None),
        }
    }

    /// Shares this room's current outbound Megolm session with the given users, rotating to a new
    /// one first if none exists yet or the old one needs rotating — matching how
    /// cluborbit-web's client.sendMessage implicitly does this via matrix-js-sdk before every send
    /// to a room whose key hasn't been shared with a member yet. `ensure_sessions_for_users` must
    /// have already been called (and its resulting keys_claim round trip completed) for these
    /// users, or sharing will simply skip devices with no session.
    ///
    /// Returns the to-device requests that actually carry the room key. Like keys_claim, these are
    /// NOT part of `outgoing_requests` — matrix-sdk-crypto hands them back only here — so the caller
    /// must send every one and feed each response to `mark_request_as_sent` (kind "to_device").
    /// Dropping them means the key never leaves this device and every recipient sees "unable to
    /// decrypt" for everything this device sends.
    pub async fn share_room_key(&self, room_id: String, user_ids: Vec<String>) -> Result<Vec<PendingRequest>, CryptoError> {
        let room_id = <&RoomId>::try_from(room_id.as_str())
            .map_err(|e: ruma::IdParseError| CryptoError { message: e.to_string() })?;
        let users: Vec<_> = user_ids.iter().map(|u| UserId::parse(u.as_str())).collect::<Result<_, _>>()?;
        let requests = self
            .machine
            .share_room_key(room_id, users.iter().map(|u| u.as_ref()), EncryptionSettings::default())
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        let mut pending = Vec::with_capacity(requests.len());
        for req in requests {
            // Same conversion outgoing_request_entry does for queued to-device requests; the txn_id
            // doubles as the request id mark_request_as_sent expects.
            let ruma_request = send_event_to_device::v3::Request::new_raw(
                req.event_type.clone(),
                req.txn_id.clone(),
                req.messages.clone(),
            );
            pending.push(request_to_pending(req.txn_id.to_string(), "to_device", ruma_request)?);
        }
        Ok(pending)
    }

    /// Megolm-encrypts a plaintext event for the given room — panics (per matrix-sdk-crypto's own
    /// contract) if `share_room_key` hasn't been called for this room first. `event_type` and
    /// `content_json` are the plaintext event's own type ("m.room.message") and content, exactly
    /// as they'd be sent to an unencrypted room; the returned JSON is the content of the
    /// `m.room.encrypted` event to send instead.
    pub async fn encrypt_room_event(
        &self,
        room_id: String,
        event_type: String,
        content_json: String,
    ) -> Result<String, CryptoError> {
        let room_id = <&RoomId>::try_from(room_id.as_str())
            .map_err(|e: ruma::IdParseError| CryptoError { message: e.to_string() })?;
        let content: Raw<ruma::events::AnyMessageLikeEventContent> =
            Raw::from_json_string(content_json)?;
        let encrypted = self
            .machine
            .encrypt_room_event_raw(room_id, event_type.as_str(), &content)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(encrypted.json().get().to_string())
    }

    /// Decrypts an `m.room.encrypted` event, given the room it came from and the full raw event
    /// JSON exactly as received (including type, sender, content, etc. — not just the content).
    /// Returns the decrypted plaintext event content as a JSON string.
    pub async fn decrypt_room_event(&self, room_id: String, event_json: String) -> Result<String, CryptoError> {
        let room_id = <&RoomId>::try_from(room_id.as_str())
            .map_err(|e: ruma::IdParseError| CryptoError { message: e.to_string() })?;
        let event: Raw<EncryptedEvent> = Raw::from_json_string(event_json)?;
        // Untrusted: decrypt regardless of the sender device's cross-signing state — matches how
        // cluborbit-web currently behaves too (verification isn't enforced as a precondition for
        // decryption there either yet).
        let decryption_settings =
            DecryptionSettings { sender_device_trust_requirement: TrustRequirement::Untrusted };
        let decrypted = self
            .machine
            .decrypt_room_event(&event, room_id, &decryption_settings)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(decrypted.event.json().get().to_string())
    }

    /// Whether this account's cross-signing identity (master + self-signing + user-signing keys)
    /// is already set up — check this before calling `bootstrap_cross_signing` to skip the extra
    /// request round trip on every login after the first.
    pub async fn is_cross_signing_ready(&self) -> bool {
        self.machine.cross_signing_status().await.is_complete()
    }

    /// Creates (or re-publishes) this account's cross-signing identity, matching
    /// cluborbit-web's `crypto.bootstrapCrossSigning()` call in chatService.js — once done, this
    /// device (and any other cross-signed device on the account) shows up as "verified" to other
    /// users instead of relying on per-device trust-on-first-use. Safe to call on every login:
    /// matrix-sdk-crypto only generates new keys the first time; later calls just re-publish the
    /// existing ones. Uploading the signing keys requires user-interactive auth — this preemptively
    /// attaches password auth (the same UIA shortcut chatService.js's authUploadDeviceSigningKeys
    /// takes on retry, just supplied up front instead of after a 401, to skip that extra round
    /// trip), using the same account password already used to log in and to open the crypto store.
    pub async fn bootstrap_cross_signing(&self, password: String) -> Result<CrossSigningBootstrap, CryptoError> {
        let requests = self
            .machine
            .bootstrap_cross_signing(false)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;

        let upload_keys_req = match &requests.upload_keys_req {
            Some(req) => outgoing_request_entry(req.request_id().to_string(), req.request())?,
            None => None,
        };

        let signing = requests.upload_signing_keys_req;
        let mut signing_req = upload_signing_keys::v3::Request::new();
        signing_req.master_key = signing.master_key.as_ref().map(cross_signing_key_to_raw).transpose()?;
        signing_req.self_signing_key =
            signing.self_signing_key.as_ref().map(cross_signing_key_to_raw).transpose()?;
        signing_req.user_signing_key =
            signing.user_signing_key.as_ref().map(cross_signing_key_to_raw).transpose()?;
        signing_req.auth = Some(AuthData::Password(UiaaPassword::new(
            UserIdentifier::UserIdOrLocalpart(self.machine.user_id().to_string()),
            password,
        )));
        let upload_signing_keys_req =
            request_to_pending(TransactionId::new().to_string(), "signing_keys_upload", signing_req)?;

        let upload_signatures_req = request_to_pending(
            TransactionId::new().to_string(),
            "signature_upload",
            requests.upload_signatures_req,
        )?;

        Ok(CrossSigningBootstrap { upload_keys_req, upload_signing_keys_req, upload_signatures_req })
    }

    /// Imports this account's private cross-signing keys, recovered via SSSS, instead of
    /// `bootstrap_cross_signing` generating a brand new identity that would conflict with one
    /// another device (like cluborbit-web) already published — call this first, and only fall
    /// back to `bootstrap_cross_signing` if this account's secret storage has none of these secrets
    /// stored yet (a genuinely first-ever setup). Each argument is that secret's decrypted
    /// plaintext (an unpadded base64 Ed25519 seed, via `ssss_decrypt_secret`) — pass whichever of
    /// the three were actually present; matrix-sdk-crypto imports only the ones given. Returns
    /// whether the identity is now fully usable (all three present, locally, after this import).
    pub async fn import_cross_signing_keys(
        &self,
        master_key: Option<String>,
        self_signing_key: Option<String>,
        user_signing_key: Option<String>,
    ) -> Result<bool, CryptoError> {
        let export = CrossSigningKeyExport { master_key, self_signing_key, user_signing_key };
        let status = self
            .machine
            .import_cross_signing_keys(export)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(status.is_complete())
    }

    /// Activates this account's existing server-side key backup using its decryption key
    /// (recovered via SSSS) — `version_info_json` is the raw JSON body of
    /// `GET /room_keys/version`, used both to read the backup's version string and to verify the
    /// key actually matches its published public key before trusting it for anything; a mismatch
    /// (wrong password, or the backup was reset since) makes this a safe no-op instead of
    /// activating against the wrong backup. Returns whether it was activated — call
    /// `import_room_keys_from_backup` next to actually pull the existing keys in.
    pub async fn enable_key_backup_from_secret(
        &self,
        decryption_key_base64: String,
        version_info_json: String,
    ) -> Result<bool, CryptoError> {
        let key = BackupDecryptionKey::from_base64(&decryption_key_base64)
            .map_err(|e| CryptoError { message: e.to_string() })?;

        #[derive(serde::Deserialize)]
        struct VersionField {
            version: String,
        }
        let version_field: VersionField = serde_json::from_str(&version_info_json)?;
        let info: RoomKeyBackupInfo = serde_json::from_str(&version_info_json)?;

        if !key.backup_key_matches(&info) {
            return Ok(false);
        }

        self.machine
            .backup_machine()
            .save_decryption_key(Some(key.clone()), Some(version_field.version.clone()))
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;

        let public_key = key.megolm_v1_public_key();
        public_key.set_version(version_field.version);
        self.machine
            .backup_machine()
            .enable_backup_v1(public_key)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;

        Ok(true)
    }

    /// The second half of restoring an existing backup: given the raw JSON body of
    /// `GET /room_keys/keys?version=<version>` (fetch this only after `enable_key_backup_from_secret`
    /// returned true), decrypts every session with the now-active backup decryption key and
    /// imports them — this is what actually makes message history from before this device existed
    /// readable again. Returns how many session keys were imported.
    pub async fn import_room_keys_from_backup(&self, keys_response_json: String) -> Result<u32, CryptoError> {
        let backup_keys = self
            .machine
            .backup_machine()
            .get_backup_keys()
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        let decryption_key = backup_keys.decryption_key.ok_or_else(|| CryptoError {
            message: "No backup decryption key is active — call enable_key_backup_from_secret first".to_string(),
        })?;

        let response: get_backup_keys::v3::Response = parse_response(keys_response_json)?;

        let mut room_keys: BTreeMap<OwnedRoomId, BTreeMap<String, BackedUpRoomKey>> = BTreeMap::new();
        for (room_id, room_backup) in response.rooms {
            let mut sessions = BTreeMap::new();
            for (session_id, raw_data) in room_backup.sessions {
                let Ok(data) = raw_data.deserialize() else { continue };
                if let Ok(backed_up) = decryption_key.decrypt_session_data(data.session_data) {
                    sessions.insert(session_id, backed_up);
                }
            }
            if !sessions.is_empty() {
                room_keys.insert(room_id, sessions);
            }
        }

        #[allow(deprecated)]
        let result = self
            .machine
            .backup_machine()
            .import_backed_up_room_keys(room_keys, |_, _| {})
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;

        Ok(result.imported_count as u32)
    }

    /// Whether a server-side key backup is active on this machine (so `backup_room_keys` uploads).
    pub async fn is_key_backup_enabled(&self) -> bool {
        self.machine.backup_machine().enabled().await
    }

    /// The next batch (the crypto engine caps it at 100) of room keys not yet in the active
    /// server-side backup, already encrypted to the backup's public key, as a
    /// `PUT /room_keys/keys` request — None when everything is backed up (or no backup is active).
    /// Send it and report back via `mark_request_as_sent` (kind "keys_backup"); repeat until None.
    /// This is what makes every key this device receives or creates recoverable after a reinstall.
    pub async fn backup_room_keys(&self) -> Result<Option<PendingRequest>, CryptoError> {
        let Some((txn_id, request)) = self
            .machine
            .backup_machine()
            .backup()
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?
        else {
            return Ok(None);
        };
        let ruma_request = add_backup_keys::v3::Request::new(request.version, request.rooms);
        Ok(Some(request_to_pending(txn_id.to_string(), "keys_backup", ruma_request)?))
    }

    /// How many room keys this store holds, and how many of those are in the active backup.
    pub async fn room_key_counts(&self) -> Result<RoomKeyCountsInfo, CryptoError> {
        let counts = self
            .machine
            .backup_machine()
            .room_key_counts()
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(RoomKeyCountsInfo { total: counts.total as u32, backed_up: counts.backed_up as u32 })
    }

    /// Generates a brand-new backup key and the signed body for `POST /room_keys/version` - only
    /// for when the account has no usable backup at all. The caller stores the returned decryption
    /// key in secret storage (as `m.megolm_backup.v1`) and then activates it with
    /// `enable_key_backup_from_secret`, exactly like a restored backup.
    pub async fn new_key_backup(&self) -> Result<NewKeyBackup, CryptoError> {
        let key = BackupDecryptionKey::new().map_err(|e| CryptoError { message: e.to_string() })?;
        let mut info = key.to_backup_info();
        self.machine
            .backup_machine()
            .sign_backup(&mut info)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(NewKeyBackup {
            decryption_key_base64: key.to_base64(),
            create_version_body_json: serde_json::to_string(&info)?,
        })
    }

    /// This account's private cross-signing keys (unpadded base64 seeds), for storing in newly
    /// created secret storage so other devices can recover the same identity. None if absent.
    pub async fn export_cross_signing_keys(&self) -> Result<Option<CrossSigningSecrets>, CryptoError> {
        let export = self
            .machine
            .export_cross_signing_keys()
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(export.map(|e| CrossSigningSecrets {
            master_key: e.master_key.clone(),
            self_signing_key: e.self_signing_key.clone(),
            user_signing_key: e.user_signing_key.clone(),
        }))
    }
}

