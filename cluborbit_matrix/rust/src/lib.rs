impl CryptoSession {
    /// Opens (creating if needed) a SQLite-backed OlmMachine for (user_id, device_id) rooted at
    /// store_path — a directory the Dart side is responsible for pointing at somewhere private
    /// and durable (path_provider's app-support directory, matching how cluborbit-web namespaces
    /// its IndexedDB store per-uid). passphrase encrypts the store at rest; pass the Club Orbit
    /// account password the same way chatService.js derives its secret-storage key from it, so
    /// there's nothing new for the user to remember.
    pub async fn create(
        user_id: String,
        device_id: String,
        store_path: String,
        passphrase: String,
    ) -> Result<CryptoSession, CryptoError> {
        let user_id = UserId::parse(user_id.as_str())?;
        let device_id: &DeviceId = device_id.as_str().into();
        let store = matrix_sdk_sqlite::SqliteCryptoStore::open(store_path, Some(passphrase.as_str()))
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        let machine = OlmMachine::with_store(&user_id, device_id, store, None)
            .await
            .map_err(|e| CryptoError { message: e.to_string() })?;
        Ok(CryptoSession {
            machine: std::mem::ManuallyDrop::new(machine),
            runtime: tokio::runtime::Handle::try_current().ok(),
        })
    }

    /// This device's own Curve25519 (used for Olm sessions) and Ed25519 (used for signing) keys.
    pub fn identity_keys(&self) -> IdentityKeys {
        let keys = self.machine.identity_keys();
        IdentityKeys {
            curve25519: keys.curve25519.to_base64(),
            ed25519: keys.ed25519.to_base64(),
        }
    }

    /// The device ID this machine was created with, echoed back for sanity-checking from Dart.
    pub fn device_id(&self) -> String {
        self.machine.device_id().to_string()
    }
}

/// Trivial call with no crypto involved — the first thing to wire up and call from Dart, purely
/// to prove the Rust ⇄ Dart ⇄ (eventually) Android .so pipeline works before layering in
/// anything that actually touches key material.
pub fn native_crypto_engine_version() -> String {
    env!("CARGO_PKG_VERSION").to_string()
}

// Free functions (not tied to a CryptoSession) implementing Secure Secret Storage and Sharing
// (SSSS / "4S") — see secret_storage.rs for the byte-level spec this is matched against. These
// don't touch the OlmMachine at all: Dart fetches the relevant account-data events itself
// (MatrixLowLevelClient.getAccountData) and calls these to do the actual key derivation/
// decryption, then hands the results to CryptoSession's import_cross_signing_keys /
// enable_key_backup_from_secret for the parts that do need the machine.

/// Step 1: turns the account password into this account's 32-byte 4S master key, given the
/// iterations/salt published (in the clear) on this account's `m.secret_storage.key.<id>` event.
pub fn ssss_derive_master_key(passphrase: String, salt: String, iterations: u32) -> Vec<u8> {
    secret_storage::derive_master_key_from_passphrase(&passphrase, &salt, iterations).to_vec()
}

/// Verifies a derived master key against the same `m.secret_storage.key.<id>` event's published
/// check value, before it's trusted for anything — a wrong password (or salt/iterations pulled
/// from the wrong key id) simply returns false here rather than going on to decrypt anything.
pub fn ssss_check_master_key(master_key: Vec<u8>, check_iv_base64: String, expected_mac_base64: String) -> bool {
    let Ok(key) = <[u8; 32]>::try_from(master_key.as_slice()) else { return false };
    secret_storage::check_master_key(&key, &check_iv_base64, &expected_mac_base64)
}

/// Decrypts one secret-storage item — `secret_name` must be the secret's own account-data event
/// type (e.g. "m.megolm_backup.v1", "m.cross_signing.master"), and iv/ciphertext/mac come from
/// that event's `content.encrypted.<keyId>` payload.
pub fn ssss_decrypt_secret(
    master_key: Vec<u8>,
    secret_name: String,
    iv_base64: String,
    ciphertext_base64: String,
    mac_base64: String,
) -> Result<String, CryptoError> {
    let key = <[u8; 32]>::try_from(master_key.as_slice())
        .map_err(|_| CryptoError { message: "SSSS master key must be 32 bytes".to_string() })?;
    let payload = secret_storage::EncryptedPayload {
        iv: iv_base64,
        ciphertext: ciphertext_base64,
        mac: mac_base64,
    };
    secret_storage::decrypt_secret(&payload, &key, &secret_name)
}

/// A newly created, password-derived secret-storage key - for an account that has none yet. The
/// Dart side publishes `m.secret_storage.key.<key_id>` (algorithm, passphrase {m.pbkdf2, salt,
/// iterations, bits: 256}, iv, mac) and `m.secret_storage.default_key`, then encrypts secrets
/// with `master_key`. Same scheme and parameters as cluborbit-web's
/// createRecoveryKeyFromPassphrase (500,000 PBKDF2-SHA512 iterations, 32-char salt), so the web
/// derives the identical key from the same password and can read everything stored under it.
pub struct NewSecretStorageKey {
    pub key_id: String,
    pub salt: String,
    pub iterations: u32,
    pub check_iv: String,
    pub check_mac: String,
    pub master_key: Vec<u8>,
}

pub fn ssss_create_key_from_passphrase(passphrase: String) -> NewSecretStorageKey {
    const ITERATIONS: u32 = 500_000;
    let salt = secret_storage::random_string(32);
    let master_key = secret_storage::derive_master_key_from_passphrase(&passphrase, &salt, ITERATIONS);
    let check = secret_storage::key_check(&master_key);
    NewSecretStorageKey {
        key_id: secret_storage::random_string(32),
        salt,
        iterations: ITERATIONS,
        check_iv: check.iv,
        check_mac: check.mac,
        master_key: master_key.to_vec(),
    }
}

/// `{iv, ciphertext, mac}` for one secret, ready for `content.encrypted.<keyId>`.
pub struct EncryptedSecret {
    pub iv: String,
    pub ciphertext: String,
    pub mac: String,
}

/// Encrypts one secret (e.g. "m.megolm_backup.v1") for storing in account data - the inverse of
/// `ssss_decrypt_secret`.
pub fn ssss_encrypt_secret(
    master_key: Vec<u8>,
    secret_name: String,
    plaintext: String,
) -> Result<EncryptedSecret, CryptoError> {
    let key = <[u8; 32]>::try_from(master_key.as_slice())
        .map_err(|_| CryptoError { message: "SSSS master key must be 32 bytes".to_string() })?;
    let payload = secret_storage::encrypt_secret(&key, &secret_name, plaintext.as_bytes());
    Ok(EncryptedSecret { iv: payload.iv, ciphertext: payload.ciphertext, mac: payload.mac })
}

/// The result of `encrypt_attachment` — everything the `m.room.message` event's `file` field
/// needs (the `EncryptedFile` object from the Matrix spec) except `url`, which the Dart side fills
/// in once the ciphertext has actually been uploaded to the media repo.
pub struct EncryptedAttachment {
    pub ciphertext: Vec<u8>,
    pub key_base64: String,
    pub iv_base64: String,
    pub sha256_base64: String,
}

/// Encrypts a media attachment (image/video/file/audio bytes) before upload, per the Matrix
/// spec's "Sending encrypted attachments" — matches cluborbit-web's own attachment encryption
/// byte-for-byte (see rust/src/attachment_crypto.rs), so a photo sent from either client decrypts
/// correctly on the other.
pub fn encrypt_attachment(plaintext: Vec<u8>) -> EncryptedAttachment {
    let result = attachment_crypto::encrypt_attachment(&plaintext);
    EncryptedAttachment {
        ciphertext: result.ciphertext,
        key_base64: result.key_base64,
        iv_base64: result.iv_base64,
        sha256_base64: result.sha256_base64,
    }
}

/// Decrypts a downloaded attachment ciphertext using the `key`/`iv` from the event's `content.file`
/// — `sha256_base64` should be `content.file.hashes.sha256` when present (it always is for an
/// attachment this app or any spec-compliant Matrix client produced); verified before decrypting,
/// never skipped when available.
pub fn decrypt_attachment(
    ciphertext: Vec<u8>,
    key_base64: String,
    iv_base64: String,
    sha256_base64: Option<String>,
) -> Result<Vec<u8>, CryptoError> {
    attachment_crypto::decrypt_attachment(&ciphertext, &key_base64, &iv_base64, sha256_base64.as_deref())
}
