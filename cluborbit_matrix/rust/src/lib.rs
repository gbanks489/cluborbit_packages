/// Converts an outgoing API request (whatever ruma-typed struct a specific endpoint uses) into a
/// method + path + JSON body — Dart's REST client already knows how to make an authenticated HTTP
/// call given those three things, so this keeps every endpoint-specific detail (exact path,
/// method, how fields map to the wire body) inside Rust, checked against ruma's real types,
/// instead of duplicated by hand in Dart. base_url is a placeholder — the real one lives in Dart's
/// client config — since only the path is kept from the result.
fn request_to_pending<R: OutgoingRequest>(id: String, kind: &str, req: R) -> Result<PendingRequest, CryptoError> {
    let http_req: http::Request<Vec<u8>> = req
        .try_into_http_request(
            "https://dummy.invalid",
            SendAccessToken::IfRequired("unused"),
            &[MatrixVersion::V1_1],
        )
        .map_err(|e| CryptoError { message: e.to_string() })?;
    let method = http_req.method().to_string();
    let path = http_req.uri().path_and_query().map(|pq| pq.to_string()).unwrap_or_default();
    let body_json = String::from_utf8(http_req.into_body()).map_err(|e| CryptoError { message: e.to_string() })?;
    Ok(PendingRequest { id, kind: kind.to_string(), method, path, body_json })
}

/// The inverse: parses the JSON body Dart got back from the homeserver into the typed response a
/// specific endpoint expects, via the same ruma machinery in reverse.
fn parse_response<R: IncomingResponse>(response_json: String) -> Result<R, CryptoError> {
    let http_response = http::Response::builder()
        .status(200)
        .body(response_json.into_bytes())
        .map_err(|e| CryptoError { message: e.to_string() })?;
    R::try_from_http_response(http_response).map_err(|e| CryptoError { message: e.to_string() })
}

/// Re-tags a matrix-sdk-crypto `CrossSigningKey` (its own mirror of the wire type, produced by
/// `bootstrap_cross_signing`) as `Raw<ruma's CrossSigningKey>` for the upload request — `Raw` is
/// just phantom-typed JSON text, so a plain serialize/re-tag round trip is enough; the two types
/// are guaranteed to share the same JSON shape (that's the entire point of matrix-sdk-crypto's
/// mirror types), no field-by-field conversion needed.
fn cross_signing_key_to_raw(
    key: &matrix_sdk_crypto::types::CrossSigningKey,
) -> Result<Raw<ruma::encryption::CrossSigningKey>, CryptoError> {
    Ok(Raw::from_json_string(serde_json::to_string(key)?)?)
}

/// Converts one of the machine's queued outgoing requests into the method/path/body shape Dart
/// sends over HTTP — shared between `outgoing_requests` (the normal per-sync pump) and
/// `bootstrap_cross_signing` (which hands back an `AnyOutgoingRequest` for the device-key upload
/// outside that pump, using the exact same request type).
fn outgoing_request_entry(id: String, request: &AnyOutgoingRequest) -> Result<Option<PendingRequest>, CryptoError> {
    Ok(match request {
        AnyOutgoingRequest::KeysUpload(req) => Some(request_to_pending(id, "keys_upload", req.clone())?),
        AnyOutgoingRequest::KeysQuery(req) => {
            // matrix-sdk-crypto's KeysQueryRequest is a "customized version" of ruma's own
            // get_keys::v3::Request (its own doc comment says so) with identical fields, so build
            // one of those from it — only the real ruma type implements OutgoingRequest, which is
            // what actually knows the correct wire shape/path.
            let ruma_request = {
                // #[non_exhaustive] blocks struct-literal syntax (even with ..Default::default())
                // from outside the defining crate — build via Default then assign fields instead.
                let mut r = get_keys::v3::Request::default();
                r.timeout = req.timeout;
                r.device_keys = req.device_keys.clone();
                r
            };
            Some(request_to_pending(id, "keys_query", ruma_request)?)
        }
        AnyOutgoingRequest::KeysClaim(req) => Some(request_to_pending(id, "keys_claim", req.clone())?),
        AnyOutgoingRequest::ToDeviceRequest(req) => {
            // Same story as KeysQuery — matrix-sdk-crypto's ToDeviceRequest is its own "customized
            // version" of ruma's send_event_to_device::v3::Request with matching fields.
            let ruma_request = send_event_to_device::v3::Request::new_raw(
                req.event_type.clone(),
                req.txn_id.clone(),
                req.messages.clone(),
            );
            Some(request_to_pending(id, "to_device", ruma_request)?)
        }
        AnyOutgoingRequest::SignatureUpload(req) => {
            Some(request_to_pending(id, "signature_upload", req.clone())?)
        }
        // RoomMessage (interactive-verification-in-room) isn't needed without a verification UI.
        AnyOutgoingRequest::RoomMessage(_) => None,
    })
}

/// One device's crypto state — the Rust-side handle Dart holds onto for every other call. Opaque
/// to Dart (flutter_rust_bridge generates a thin wrapper around a pointer to this), since an
/// OlmMachine can't be meaningfully copied or serialized.
pub struct CryptoSession {
    // ManuallyDrop so Drop (below) can release it inside the async runtime.
    machine: std::mem::ManuallyDrop<OlmMachine>,
    // The runtime this session was created on (flutter_rust_bridge's async executor).
    runtime: Option<tokio::runtime::Handle>,
}

impl Drop for CryptoSession {
    /// Dart releases this handle from its own thread (dispose(), or the GC finalizer), where no
    /// tokio runtime is active - but the SQLite store's connection pool can only be dropped
    /// inside one, and dropping it outside aborts the whole process (which silently killed the
    /// closed-app notification decrypt). So enter the creating runtime for the drop.
    fn drop(&mut self) {
        let _guard = self.runtime.as_ref().map(|handle| handle.enter());
        // SAFETY: dropped exactly once, here, and never accessed afterwards.
        unsafe { std::mem::ManuallyDrop::drop(&mut self.machine) };
    }
}

